  FOR SELECT TO authenticated
  USING (is_admin((SELECT auth.uid())));

CREATE POLICY activity_logs_admin_system ON activity_logs
  FOR SELECT TO authenticated
  USING (is_admin((SELECT auth.uid())) AND category = 'system');

-- RLS: 写入
