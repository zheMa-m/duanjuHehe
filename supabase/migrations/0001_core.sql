-- RLS: 用户查看自己的认证日�?
CREATE POLICY activity_logs_user_select_own ON activity_logs
  FOR SELECT TO authenticated
  USING ((SELECT auth.uid()) = user_id AND category = 'auth');

-- RLS: 管理员查�?写入所有日�?
